import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { applicationSource } from '../client/scripts/source.ts';

const toolRoot = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(path.join(toolRoot, 'client/package.json'));

function sourceFiles(root: string): string[] {
  // Inspect the supplied source tree, even when the sandbox denies Git metadata.
  // Do not apply .gitignore: ordinary ignored source files still need inspection.
  const caches = new Set(['node_modules', '.git', '.tmp', '.pnpm-store']);
  const outputs = new Set(['client/dist', 'server/bin']);
  const files: string[] = [];
  const walk = (directory: string) => {
    for (const entry of fs.readdirSync(path.join(root, directory), {
      withFileTypes: true,
    })) {
      const file = directory ? `${directory}/${entry.name}` : entry.name;
      if (caches.has(entry.name) || outputs.has(file)) continue;
      if (entry.isDirectory()) walk(file);
      else if (entry.isFile() || entry.isSymbolicLink()) files.push(file);
    }
  };
  walk('');
  return files;
}

export async function checkTypeScriptQuality(
  mode: 'format' | 'lint' | 'exports',
  root = toolRoot,
): Promise<number> {
  let exitCode = 0;
  const files = [...new Set(sourceFiles(root))]
    .filter((file) => /\.(?:[cm]?ts|[cm]?js)$/.test(file))
    .filter((file) => fs.existsSync(path.join(root, file)))
    .sort();
  if (!files.length) throw Error('検査するTypeScript/JavaScriptがありません。');
  const application = applicationSource(path.join(root, 'client'));
  const app = 'client/src/ui/app.ts';
  const parts = new Set(
    application.parts.map((name) => `client/src/ui/${name}`),
  );
  for (const file of [app, ...parts]) {
    if (!files.includes(file))
      throw Error(`画面の結合元が検査一覧にありません: ${file}`);
  }
  // These generated modules are checked against their generators by fixed tests.
  // Preserve reproducible generated bytes; still lint and inspect their exports.
  const generatedFormat = new Set([
    'scripts/lib/consultation-link-output.generated.ts',
    'scripts/lib/desk-contract.generated.ts',
    'shared/src/attention-split.generated.ts',
    'shared/src/consultation-spec.generated.ts',
  ]);
  const text = (file: string) => fs.readFileSync(path.join(root, file), 'utf8');

  if (mode === 'format') {
    const prettier = require('prettier');
    for (const file of files) {
      if (generatedFormat.has(file)) continue;
      if (
        !(await prettier.check(text(file), {
          filepath: path.join(root, file),
          singleQuote: true,
        }))
      ) {
        console.error(`整形が必要です: ${file}`);
        exitCode = 1;
      }
    }
  } else if (mode === 'lint') {
    const { ESLint } = require('eslint');
    const js = require('@eslint/js');
    const tseslint = require('typescript-eslint');
    const eslint = new ESLint({
      cwd: root,
      overrideConfigFile: true,
      ignore: false,
      overrideConfig: [
        { files: ['**/*.{ts,mts,cts,js,mjs,cjs}'] },
        js.configs.recommended,
        ...tseslint.configs.recommended,
        {
          rules: {
            // Dynamic JSON boundaries keep their established types; tsc owns type
            // policy. This gate adds unused/unreachable/error checks, not a type
            // migration of existing API and test adapters.
            '@typescript-eslint/no-explicit-any': 'off',
            // TypeScript only reports unreachable code when explicitly configured.
            // The recommended TS config disables the core rule, so restore it.
            'no-unreachable': 'error',
            '@typescript-eslint/no-unused-vars': [
              'error',
              {
                argsIgnorePattern: '^_',
                destructuredArrayIgnorePattern: '^_',
              },
            ],
            // Public errors deliberately omit private causes. Requiring cause
            // would change the existing redaction contract.
            'preserve-caught-error': 'off',
            'no-empty': ['error', { allowEmptyCatch: true }],
            'no-irregular-whitespace': ['error', { skipTemplates: true }],
          },
        },
      ],
    });
    for (const file of files) {
      // 分割された宣言はbuildと同じ順序で一度だけ検査する。
      if (parts.has(file)) continue;
      const source = file === app ? application.source : text(file);
      const results = await eslint.lintText(source, {
        filePath: path.join(root, file),
      });
      for (const result of results) {
        for (const message of result.messages) {
          let location = `${file}:${message.line ?? 1}:${message.column ?? 1}`;
          if (file === app && message.line) {
            const offset =
              source
                .split('\n')
                .slice(0, message.line - 1)
                .reduce((length, line) => length + line.length + 1, 0) +
              (message.column ?? 1) -
              1;
            const part = application.locations.find(
              (item) => offset >= item.start && offset < item.end,
            );
            if (part) {
              const line = source.slice(part.start, offset).split('\n').length;
              location = `${path.relative(root, part.file)}:${line}`;
            }
          }
          console.error(
            `${location}: ${message.ruleId ?? 'parse'} ${message.message}`,
          );
        }
        if (result.errorCount || result.warningCount) exitCode = 1;
      }
    }
  } else {
    // Knipにはビルド時のモジュールを再現した一時ツリーを渡す。
    // partsを無視するのではなくapp.tsへ結合する。未使用exportは入口も検査する。
    fs.mkdirSync(path.join(root, '.tmp'), { recursive: true });
    const snapshot = fs.mkdtempSync(path.join(root, '.tmp/ts-quality-'));
    try {
      const project = files.filter((file) => !parts.has(file));
      for (const file of project) {
        const destination = path.join(snapshot, file);
        fs.mkdirSync(path.dirname(destination), { recursive: true });
        fs.writeFileSync(
          destination,
          file === app ? application.source : text(file),
        );
      }
      const entry = project.filter(
        (file) =>
          /^scripts\/[^/]+\.[cm]?ts$/.test(file) ||
          // シェル入口から直接起動される CommonJS プログラム。
          file === 'scripts/public-source-send.cjs' ||
          file === 'scripts/run-public-source-jobs.cjs' ||
          file === 'scripts/scan-public-source-candidates.cjs' ||
          file === 'scripts/refresh-public-source-mirrors.cjs' ||
          /^(?:deploy|skills)\/.*\.[cm]?ts$/.test(file) ||
          /(?:^|\/)test\/.*\.test\.[cm]?ts$/.test(file) ||
          /^client\/scripts\/[^/]+\.ts$/.test(file) ||
          file === app ||
          file === 'client/src/ui/sw.ts' ||
          // Chromium fixtureはreadFile/compileSourceで読み込まれる入口。
          file === 'client/test/repository-display-browser.ts' ||
          file ===
            'server/internal/projects/templates/deploy/node/src/server.ts',
      );
      // 公開互換入口は利用側がこのcheckoutの外にもある。実装を切り出しても
      // 再exportを残す契約（request-list内の注記、docs/chat-operations.md）を表す。
      // 名前のない全体ignoreではなく、公開するmoduleだけを読取側として接続する。
      const publicModules = [
        'client/src/ui/request-list.ts',
        'client/src/ui/request-classification.ts',
        'scripts/chat-turn-checks.ts',
        'scripts/desk-client.ts',
        'scripts/desk-alerts.ts',
        // docs/api-compatibility.md: 公開wire型。Goのcontract試験も契約を確認する。
        'api/types.ts',
      ];
      const ts = require('typescript');
      // namespaceを渡すだけではKnipは各exportの使用とみなさないため、公開入口の
      // 宣言と再exportを構文解析し、名前付きの読取をsnapshotだけに生成する。
      const publicExports = (
        file: string,
        seen = new Set<string>(),
      ): Map<string, boolean> => {
        if (seen.has(file)) return new Map();
        seen.add(file);
        const names = new Map<string, boolean>();
        const source = ts.createSourceFile(
          file,
          text(file),
          ts.ScriptTarget.Latest,
          true,
        );
        for (const statement of source.statements) {
          if (ts.isExportDeclaration(statement)) {
            if (
              statement.exportClause &&
              ts.isNamedExports(statement.exportClause)
            ) {
              for (const item of statement.exportClause.elements)
                names.set(
                  item.name.text,
                  !!(statement.isTypeOnly || item.isTypeOnly),
                );
            } else if (!statement.exportClause && statement.moduleSpecifier) {
              const target = path.posix.normalize(
                path.posix.join(
                  path.posix.dirname(file),
                  statement.moduleSpecifier.text,
                ),
              );
              const resolved =
                project.find((candidate) => candidate === target) ??
                project.find(
                  (candidate) =>
                    candidate ===
                    target.replace(/\.js$/, '.ts').replace(/\.mjs$/, '.mts'),
                );
              if (!resolved)
                throw Error(
                  `公開再exportの参照先がありません: ${file}: ${target}`,
                );
              for (const [name, typeOnly] of publicExports(resolved, seen))
                names.set(name, typeOnly);
            } else throw Error(`未対応の公開exportです: ${file}`);
          } else if (
            ts.getCombinedModifierFlags(statement) & ts.ModifierFlags.Export
          ) {
            if (ts.isVariableStatement(statement)) {
              for (const declaration of statement.declarationList
                .declarations) {
                if (!ts.isIdentifier(declaration.name))
                  throw Error(`公開変数の名前を解決できません: ${file}`);
                names.set(declaration.name.text, false);
              }
            } else if (statement.name && ts.isIdentifier(statement.name)) {
              names.set(
                statement.name.text,
                ts.isInterfaceDeclaration(statement) ||
                  ts.isTypeAliasDeclaration(statement),
              );
            } else throw Error(`公開宣言の名前を解決できません: ${file}`);
          }
        }
        return names;
      };
      const consumers: string[] = [];
      let publicIndex = 0;
      for (const file of publicModules.filter((file) =>
        project.includes(file),
      )) {
        for (const [name, typeOnly] of publicExports(file)) {
          const alias = `Public${publicIndex++}`;
          consumers.push(
            typeOnly
              ? `import type { ${name} as ${alias} } from './${file}'; type Use${alias} = ${alias};`
              : `import { ${name} as ${alias} } from './${file}'; void ${alias};`,
          );
        }
      }
      // Go試験内のnode -eによる動的import。実際の呼出名だけを接続する。
      // server/internal/proposals/{followup_body,priority}_test.go
      if (project.includes('shared/src/proposal-comment.ts'))
        consumers.push(
          "import { formatProposal, proposalFingerprint } from './shared/src/proposal-comment.ts'; void [formatProposal, proposalFingerprint];",
        );
      // server/internal/proposals/followup_scope_boundary_test.go
      if (project.includes('shared/src/change-scope.ts'))
        consumers.push(
          "import { parseScope } from './shared/src/change-scope.ts'; void parseScope;",
        );
      if (consumers.length) {
        const consumer = 'quality-public-consumers.ts';
        fs.writeFileSync(path.join(snapshot, consumer), consumers.join('\n'));
        entry.push(consumer);
        project.push(consumer);
      }
      const metadata = JSON.parse(
        fs.readFileSync(path.join(root, 'client/package.json'), 'utf8'),
      );
      fs.writeFileSync(
        path.join(snapshot, 'package.json'),
        JSON.stringify({
          name: 'intake-quality-snapshot',
          private: true,
          type: 'module',
          devDependencies: metadata.devDependencies,
        }),
      );
      fs.writeFileSync(
        path.join(snapshot, 'tsconfig.json'),
        JSON.stringify({
          compilerOptions: {
            target: 'ES2024',
            module: 'Preserve',
            moduleResolution: 'Bundler',
            allowImportingTsExtensions: true,
            noEmit: true,
          },
        }),
      );
      fs.writeFileSync(
        path.join(snapshot, 'knip.json'),
        JSON.stringify({ entry, project, includeEntryExports: true }),
      );
      fs.symlinkSync(
        path.join(toolRoot, 'client/node_modules'),
        path.join(snapshot, 'node_modules'),
        'dir',
      );
      const knip = require.resolve('knip/package.json');
      const result = spawnSync(
        process.execPath,
        [
          path.join(path.dirname(knip), 'bin/knip.js'),
          '--config',
          'knip.json',
          '--no-gitignore',
          '--no-progress',
          '--include',
          'files,exports,types,duplicates,unresolved',
        ],
        { cwd: snapshot, stdio: 'inherit' },
      );
      if (result.error) throw result.error;
      if (result.status !== 0) exitCode = result.status ?? 1;
    } finally {
      fs.rmSync(snapshot, { recursive: true, force: true });
    }
  }

  return exitCode;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const mode = process.argv[2];
  if (
    (mode !== 'format' && mode !== 'lint' && mode !== 'exports') ||
    process.argv.length !== 3
  ) {
    throw Error('使い方: node scripts/check-ts-quality.ts format|lint|exports');
  }
  process.exitCode = await checkTypeScriptQuality(mode);
}
