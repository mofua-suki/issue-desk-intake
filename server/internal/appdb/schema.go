// Package appdb defines the PostgreSQL application schema (CreateSchema), used
// by the test helper internal/pgtest and by production repair.
package appdb

import "strings"

type table struct{ name, definition string }

var tables = func() []table {
	var t []table
	for _, n := range strings.Fields("settings drafts todos actions close_requests close_reasons projects proposals proposal_scans decisions ai_decisions intake_error_stalls") {
		t = append(t, table{n, "id TEXT PRIMARY KEY,json TEXT NOT NULL"})
	}
	for _, n := range strings.Fields("attention_cases job_filings") {
		t = append(t, table{n, "key TEXT PRIMARY KEY,json TEXT NOT NULL"})
	}
	t = append(t,
		table{"temporary_code_records", "repo TEXT NOT NULL,item TEXT NOT NULL,stage TEXT NOT NULL,json TEXT NOT NULL,PRIMARY KEY(repo,item,stage)"},
		table{"full_test_intake", "repo TEXT PRIMARY KEY,json TEXT NOT NULL"},
		table{"api_tokens", "id TEXT PRIMARY KEY,name TEXT NOT NULL UNIQUE,hash TEXT NOT NULL UNIQUE,issued_at TEXT NOT NULL,last_used_at TEXT"},
		table{"cli_keys", "hash TEXT PRIMARY KEY,expires BIGINT NOT NULL"},
		table{"api_token_grants", "token_id TEXT PRIMARY KEY,granted_at TEXT NOT NULL"},
		table{"admin_audit", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at TEXT NOT NULL,actor TEXT NOT NULL,action TEXT NOT NULL,target TEXT NOT NULL"},
		table{"images", "id TEXT PRIMARY KEY,scope TEXT NOT NULL,message TEXT NOT NULL,json TEXT NOT NULL,bytes BYTEA NOT NULL,bound BIGINT NOT NULL DEFAULT 0"},
		table{"intake_receipts", "id TEXT PRIMARY KEY,sender TEXT NOT NULL,send_id TEXT NOT NULL,json TEXT NOT NULL,UNIQUE(sender,send_id)"},
		table{"draft_withdrawals", "sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,draft TEXT NOT NULL,project TEXT,title TEXT,operation TEXT NOT NULL,at TEXT NOT NULL,created_at TEXT,via TEXT NOT NULL,token_name TEXT,reason TEXT,parent TEXT"},
		table{"intake_error_failures", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,draft TEXT NOT NULL,gist TEXT NOT NULL,at TEXT NOT NULL,json TEXT NOT NULL"},
		table{"reply_decisions", "id TEXT PRIMARY KEY,project TEXT,draft TEXT NOT NULL,at TEXT NOT NULL,json TEXT NOT NULL"},
		table{"proxy_answers", "id TEXT PRIMARY KEY,project TEXT,draft TEXT NOT NULL,at TEXT NOT NULL,status TEXT NOT NULL,json TEXT NOT NULL"},
		table{"desk_numbers", "number BIGINT PRIMARY KEY CHECK(number>0),project TEXT NOT NULL,gitea BIGINT NOT NULL CHECK(gitea>0),assigned_at TEXT NOT NULL,UNIQUE(project,gitea)"},
		table{"desk_projects", "project TEXT PRIMARY KEY,scanned_at TEXT NOT NULL"},
		table{"desk_counter", "id BIGINT PRIMARY KEY CHECK(id=1),next BIGINT NOT NULL CHECK(next>0)"},
		table{"usage_review_rounds", "round BIGINT PRIMARY KEY,json TEXT NOT NULL"},
		table{"usage_review_acks", "round BIGINT PRIMARY KEY,at TEXT NOT NULL"},
		// Tables the retired Node application created. Go only reads them (behind a
		// table-exists check), but a production database still holds their rows, so
		// they are kept. The shapes are the ones found in production.
		table{"stall_fixes", "draft TEXT PRIMARY KEY,key TEXT NOT NULL,stall TEXT NOT NULL,filed_at TEXT NOT NULL"},
		table{"scope_records", "id TEXT PRIMARY KEY,json TEXT NOT NULL"},
		table{"usage_review_days", "date TEXT PRIMARY KEY,json TEXT NOT NULL"},
		table{"priority_review_days", "date TEXT PRIMARY KEY,json TEXT NOT NULL"},
		table{"inventory_rounds", "round BIGINT NOT NULL,project TEXT NOT NULL,json TEXT NOT NULL,PRIMARY KEY(round,project)"},
		table{"priority_review_rounds", "round BIGINT PRIMARY KEY,json TEXT NOT NULL"},
		table{"main_break_cases", "repo TEXT PRIMARY KEY,json TEXT NOT NULL"},
		table{"topic_link_removals", "a TEXT NOT NULL,b TEXT NOT NULL,draft TEXT NOT NULL,other TEXT NOT NULL,at TEXT NOT NULL,token_name TEXT,PRIMARY KEY(a,b)"},
	)
	return t
}()
