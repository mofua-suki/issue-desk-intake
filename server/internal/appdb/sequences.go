package appdb

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
)

// Design notes
//
// Every statement names its schema explicitly, so the connection's search_path
// is irrelevant here. Production keeps the application tables in the schema
// issue_desk_app_migration (the name is historical: the tables were moved there
// from SQLite on 2026-11-04); the test helper internal/pgtest uses a throwaway
// schema.
//
// Types: integers are BIGINT (epoch milliseconds in cli_keys.expires would
// overflow a PostgreSQL INTEGER).
//
// source_rowid: RowOrder(Postgres) orders by source_rowid. Rows take the next
// value of source_rowid_seq in the owning schema.

// sourceRowidColumn is the column definition every table carries; schema names the
// schema that owns source_rowid_seq (issue_desk_app_migration in production, a throwaway
// schema in the shared PostgreSQL test helper).
func sourceRowidColumn(schema string) string {
	return "source_rowid BIGINT NOT NULL UNIQUE DEFAULT nextval('" + schema + ".source_rowid_seq')"
}

// AutoincrementTables lists the tables whose id column is a PostgreSQL identity
// column the application leaves out of its INSERT.
var AutoincrementTables = []string{"intake_error_failures"}

var indexes = []string{`images (scope)`, `draft_withdrawals (at)`, `reply_decisions (project,at)`, `proxy_answers (draft)`, `proposals (id text_pattern_ops)`}

// prepareSequences creates the shared source_rowid sequence, and brings tables
// created by an earlier version up to the current design.
func prepareSequences(ctx context.Context, p *sql.Tx, schema string) error {
	if _, e := p.ExecContext(ctx, `CREATE SEQUENCE IF NOT EXISTS `+schema+`.source_rowid_seq`); e != nil {
		return errors.New("sequence creation failed")
	}
	return nil
}

func upgradeTable(ctx context.Context, p *sql.Tx, t table, schema string) error {
	target := schema + `."` + t.name + `"`
	if _, e := p.ExecContext(ctx, `ALTER TABLE `+target+` ALTER COLUMN source_rowid SET DEFAULT nextval('`+schema+`.source_rowid_seq')`); e != nil {
		return fmt.Errorf("destination upgrade failed for %s", t.name)
	}
	for _, n := range AutoincrementTables {
		if n != t.name {
			continue
		}
		// An identity column cannot be added twice, so only add it when it is missing.
		q := `DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='` + schema + `' AND table_name='` + n + `' AND column_name='id' AND is_identity='YES') THEN ALTER TABLE ` + target + ` ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY; END IF; END $$`
		if _, e := p.ExecContext(ctx, q); e != nil {
			return fmt.Errorf("destination identity failed for %s", t.name)
		}
	}
	return nil
}
