func TestLegacyFractionalFailureTimesKeepStallsArchiveAndNotificationReservation(t *testing.T) {
	s := fixture(t)
	raw, err := os.ReadFile("testdata/ai-failures-legacy-fractional.json")
	if err != nil {
		t.Fatal(err)
	}
	file := filepath.Join(s.RuntimeDir, "state", "intake-ai-failures.json")
	if err = os.MkdirAll(filepath.Dir(file), 0700); err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(file, raw, 0600); err != nil {
		t.Fatal(err)
	}
	var sent atomic.Int32
	notify := func(context.Context, map[string]any) (map[string]any, error) { sent.Add(1); return nil, nil }
	observer := NewAIFailures(context.Background(), s.RuntimeDir, notify)
	s.AIAlerts = observer.Alerts
	rows, err := s.Stalls(context.Background())
	if err != nil || len(rows) != 1 || fleet.Object(rows[0])["id"] != "intake-ai-legacy-reserved" || fleet.Object(rows[0])["detectedAt"] != "2026-11-01T00:00:00.000Z" {
		t.Fatal("旧正規の小数msでStallsが失敗", rows, err)
	}
	// This is the fixed prior projection, not one generated by the new observer.
	prior := map[string]any{"id": "intake-ai-legacy-reserved", "kind": "intake_ai_failure", "status": "stall_alert", "project": "mofua-suki/issue-desk", "detectedAt": "2026-11-01T00:00:00.000Z", "title": "受付AIの共通障害: 相談", "detail": "codex / gpt-6.1-terra\n対象結果の失敗3件。保存済みの説明。"}
	archive, _ := json.Marshal([]any{map[string]any{"target": "stall:intake-ai-legacy-reserved", "snapshot": prior, "fingerprint": "legacy-fingerprint"}})
	if _, err = s.DB.Exec(`INSERT INTO settings(id,json)VALUES('desk-cleanup-archive',?)`, string(archive)); err != nil {
		t.Fatal(err)
	}
	rows, err = s.Stalls(context.Background())
	if err != nil || len(rows) != 0 {
		t.Fatal("旧終了済み通知を再表示", rows, err)
	}
	after, err := os.ReadFile(file)
	if err != nil || string(after) != string(raw) || sent.Load() != 0 {
		t.Fatal("読取だけで原文または通知予約を変更", err, sent.Load())
	}
	start := time.UnixMilli(1793491200000)
	observer.Observe(ai.Observation{Step: "相談", Provider: "codex", Model: "gpt-6.1-terra", StartedAt: start, FinishedAt: start.Add(5 * time.Second), Outcome: "failed", Cause: "execution"})
	observer.Close()
	if sent.Load() != 0 {
		t.Fatal("永続済みの通知予約を再送")
	}
	var saved failureRecord
	after, _ = os.ReadFile(file)
	if err = json.Unmarshal(after, &saved); err != nil || !validFailureJSON(after) {
		t.Fatal("旧時刻を書き換え時に壊しました", err)
	}
	var active *failureRange
	for _, r := range saved.Ranges {
		if r.Incident != nil {
			active = r
		}
	}
	if active == nil || active.Samples[0].At != 1793491200000.125 || active.Incident.Detected != 1793491200000.25 || active.Incident.Notified == nil || *active.Incident.Notified != 1793491200000.625 {
		t.Fatal("小数時刻または通知fingerprintの元データを失いました", active)
	}
	old := saved.Ranges["legacy-history"].Last
	if old.Detected != -1.75 || old.Resolved == nil || *old.Resolved != 0.25 || *old.Notified != -0.5 {
		t.Fatal("有効な旧Date時刻の履歴を失いました")
	}
	restarted := NewAIFailures(context.Background(), s.RuntimeDir, notify)
	defer restarted.Close()
	s.AIAlerts = restarted.Alerts
	rows, err = s.Stalls(context.Background())
	if err != nil || len(rows) != 1 {
		t.Fatal("原因が実際に変わった通知を隠しました", rows, err)
	}
	restarted.Observe(ai.Observation{Step: "相談", Provider: "codex", Model: "gpt-6.1-terra", StartedAt: start.Add(6 * time.Second), FinishedAt: start.Add(7 * time.Second), Outcome: "success"})
	rows, err = s.Stalls(context.Background())
	if err != nil || len(rows) != 0 || sent.Load() != 0 {
		t.Fatal("検知後の実成功で解消しない、または再通知", rows, err)
	}
	var kept string
	if err = s.DB.QueryRow(`SELECT json FROM settings WHERE id='desk-cleanup-archive'`).Scan(&kept); err != nil || kept != string(archive) {
		t.Fatal("既存の終了記録を変更", err)
	}
}

func TestFailureTimeMatchesFiniteJavaScriptDateRange(t *testing.T) {
	for _, n := range []float64{0, -0.25, 0.25, -8.64e15, 8.64e15} {
		if !validFailureTime(n) {
			t.Fatal("旧Dateの有効値を拒否", n)
		}
	}
	for _, n := range []float64{math.NaN(), math.Inf(1), math.Inf(-1), 8.64e15 + 1, -8.64e15 - 1} {
		if validFailureTime(n) {
			t.Fatal("無効なDateを受理", n)
		}
	}
}

func TestFailureTimestampJSONPresenceAndTypeRemainStrict(t *testing.T) {
	legacy, err := os.ReadFile("testdata/ai-failures-legacy-fractional.json")
	if err != nil {
		t.Fatal(err)
	}
	for _, field := range []string{"sample.at", "incident.detectedAt", "incident.notifiedAt", "last.resolvedAt"} {
		for _, mutation := range []string{"missing", "null", "string"} {
			t.Run(field+"/"+mutation, func(t *testing.T) {
				var value map[string]any
				if err := json.Unmarshal(legacy, &value); err != nil {
					t.Fatal(err)
				}
				ranges := fleet.Object(value["ranges"])
				var active map[string]any
				for _, raw := range ranges {
					r := fleet.Object(raw)
					if r["incident"] != nil {
						active = r
					}
				}
				parts := strings.Split(field, ".")
				var target map[string]any
				switch parts[0] {
				case "sample":
					target = fleet.Object(fleet.List(active["samples"])[0])
				case "incident":
					target = fleet.Object(active["incident"])
				case "last":
					target = fleet.Object(fleet.Object(ranges["legacy-history"])["lastIncident"])
				}
				switch mutation {
				case "missing":
					delete(target, parts[1])
				case "null":
					target[parts[1]] = nil
				case "string":
					target[parts[1]] = "1793491200000.25"
				}
				raw, _ := json.Marshal(value)
				dir := t.TempDir()
				file := filepath.Join(dir, "state", "intake-ai-failures.json")
				if err := os.MkdirAll(filepath.Dir(file), 0700); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(file, raw, 0600); err != nil {
					t.Fatal(err)
				}
				observer := NewAIFailures(context.Background(), dir, nil)
				defer observer.Close()
				_, err := observer.Alerts(context.Background())
				optionalAbsent := field == "incident.notifiedAt" && mutation == "missing"
				if (err == nil) != optionalAbsent {
					t.Fatal("旧JSONの存在・数値型検査と異なります", err)
				}
				if !optionalAbsent {
					at := time.UnixMilli(1793491200000)
					observer.Observe(ai.Observation{Step: "相談", Provider: "codex", Model: "gpt-6.1-terra", Outcome: "failed", Cause: "schema", StartedAt: at, FinishedAt: at.Add(time.Second)})
				}
				after, err := os.ReadFile(file)
				if err != nil || string(raw) != string(after) {
					t.Fatal("読めない記録を初期化・上書きしました", err)
				}
			})
		}
	}
}

type projectAlertGitea struct{}

func (projectAlertGitea) Do(_ context.Context, method, endpoint string, _ any, out any) error {
	if method != "GET" {
		return fmt.Errorf("unexpected method: %s", method)
	}
	result := out.(*map[string]any)
	switch {
	case endpoint == "/repos/"+fleet.SystemProject:
		(*result)["default_branch"] = "trunk"
	case endpoint == "/repos/"+fleet.SystemProject+"/branches/trunk":
		(*result)["commit"] = map[string]any{"id": strings.Repeat("a", 40)}
	case strings.HasPrefix(endpoint, "/repos/"+fleet.SystemProject+"/git/trees/"):
		(*result)["tree"] = []any{map[string]any{"path": "api/openapi/spec.yaml", "type": "blob", "mode": "100644", "size": float64(81001)}}
	default:
		return fmt.Errorf("unexpected endpoint: %s", endpoint)
	}
	return nil
}

func TestConfigAlertsUseSystemProject(t *testing.T) {
	s := fixture(t)
	data, err := os.ReadFile("../../../fleet.json")
	if err != nil {
		t.Fatal(err)
	}
	var doc fleet.Document
	if err := json.Unmarshal(data, &doc); err != nil {
		t.Fatal(err)
	}
	s.Fleet = func() (fleet.Document, *fleet.Assignments, error) { return doc, nil, nil }
	s.Now = func() time.Time { return time.Date(2100, 1, 1, 0, 0, 0, 0, time.UTC) }
	s.Gitea = projectAlertGitea{}
	s.Repositories = func() ([]string, error) { return []string{fleet.SystemProject}, nil }
	for _, test := range []struct {
		name string
		read func(context.Context) ([]any, error)
	}{
		{"temporary_setting_expired", s.temporaryAlerts}, {"design_doc_near_limit", s.designDocAlerts},
	} {
		t.Run(test.name, func(t *testing.T) {
			rows, err := test.read(t.Context())
			if err != nil || len(rows) == 0 {
				t.Fatalf("alerts=%v err=%v", rows, err)
			}
			for _, raw := range rows {
				row := fleet.Object(raw)
				if row["kind"] != test.name || row["project"] != fleet.SystemProject {
					t.Fatalf("alert=%v", row)
				}
			}
		})
	}
}

