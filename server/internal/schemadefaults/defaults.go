// Package schemadefaults repairs the auto-numbering of the PostgreSQL application schema.
package schemadefaults

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"regexp"
)

var schemaName = regexp.MustCompile(`^[a-z_][a-z0-9_]{0,62}$`)

// Columns lists every column the application leaves out of its INSERT and lets
// PostgreSQL number using identity columns. appdb creates and migrates its
// schema from this list.
var Columns = []struct{ Table, Column string }{
	{"intake_error_failures", "id"},
	{"admin_audit", "id"},
	{"draft_withdrawals", "sequence"},
}

// EnsureDefaults repairs the identity (auto-numbering) columns of a PostgreSQL
// schema that was created before they existed: SQLite numbered an
// INTEGER PRIMARY KEY by itself and the application leaves such columns out of
// its INSERT, but the first PostgreSQL schema had no default for them, so every
// such INSERT failed on NOT NULL. For each column of Columns that is not
// an identity column yet, it adds GENERATED BY DEFAULT AS IDENTITY and moves the
// sequence above the largest existing value, in one transaction per table. A
// column that already is an identity column, or already has a default, and a
// table that does not exist are left alone, so running it again changes nothing.
//
// It returns the names of the tables it could not repair (never values); the
// caller logs them and keeps starting, because a failed repair must not stop the
// intake. schema must be a plain lower-case identifier.
func EnsureDefaults(ctx context.Context, db *sql.DB, schema string) ([]string, error) {
	if !schemaName.MatchString(schema) {
		return nil, errors.New("schema name is invalid")
	}
	var failed []string
	for _, c := range Columns {
		if err := ensureIdentity(ctx, db, schema, c.Table, c.Column); err != nil {
			failed = append(failed, c.Table)
		}
	}
	if len(failed) > 0 {
		return failed, fmt.Errorf("identity repair failed for %d table(s)", len(failed))
	}
	return nil, nil
}

func ensureIdentity(ctx context.Context, db *sql.DB, schema, table, column string) error {
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var identity string
	var def sql.NullString
	switch e := tx.QueryRowContext(ctx, `SELECT is_identity, column_default FROM information_schema.columns WHERE table_schema=$1 AND table_name=$2 AND column_name=$3`, schema, table, column).Scan(&identity, &def); {
	case errors.Is(e, sql.ErrNoRows):
		return nil
	case e != nil:
		return e
	}
	if identity == "YES" || def.Valid {
		return nil
	}
	target := schema + `."` + table + `"`
	if _, err = tx.ExecContext(ctx, `ALTER TABLE `+target+` ALTER COLUMN "`+column+`" ADD GENERATED BY DEFAULT AS IDENTITY`); err != nil {
		return err
	}
	q := `SELECT setval(pg_get_serial_sequence('` + schema + `."` + table + `"','` + column + `'), GREATEST(m,1), m>0) FROM (SELECT COALESCE((SELECT MAX("` + column + `") FROM ` + target + `),0) AS m) x`
	if _, err = tx.ExecContext(ctx, q); err != nil {
		return err
	}
	return tx.Commit()
}
