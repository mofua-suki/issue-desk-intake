// Package appsql contains the SQL helpers of the application store (PostgreSQL).
package appsql

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
)

type Dialect int

const (
	Postgres Dialect = iota
)

var identifier = regexp.MustCompile(`^[a-zA-Z_][a-zA-Z0-9_]*$`)

func (d Dialect) valid() bool { return d == Postgres }

// Bind converts unquoted question-mark parameters. SQL strings, identifiers,
// dollar-quoted strings, PostgreSQL E'...' strings and comments are left
// intact. PostgreSQL jsonb operators containing ? (?, ?|, ?&) cannot be told
// apart from parameters and are NOT detected: callers must not use them.
func (d Dialect) Bind(s string) (string, error) {
	if !d.valid() {
		return "", errors.New("unknown SQL dialect")
	}
	var b strings.Builder
	n := 0
	hasNumbered := false
	for i := 0; i < len(s); {
		start := i
		switch {
		case s[i] == '\'' || s[i] == '"':
			q := s[i]
			i++
			closed := false
			for i < len(s) {
				if s[i] == q {
					i++
					if i < len(s) && s[i] == q {
						i++
						continue
					}
					closed = true
					break
				}
				i++
			}
			if !closed {
				return "", errors.New("unterminated SQL quote")
			}
		case strings.HasPrefix(s[i:], "--"):
			i += 2
			for i < len(s) && s[i] != '\n' {
				i++
			}
		case strings.HasPrefix(s[i:], "/*"):
			i += 2
			depth := 1
			for i < len(s) && depth > 0 {
				if strings.HasPrefix(s[i:], "/*") {
					depth++
					i += 2
				} else if strings.HasPrefix(s[i:], "*/") {
					depth--
					i += 2
				} else {
					i++
				}
			}
			if depth != 0 {
				return "", errors.New("unterminated SQL comment")
			}
		case s[i] == '$':
			if i+1 < len(s) && s[i+1] >= '0' && s[i+1] <= '9' {
				hasNumbered = true
				i += 2
				for i < len(s) && s[i] >= '0' && s[i] <= '9' {
					i++
				}
				break
			}
			j := i + 1
			for j < len(s) && ((s[j] >= 'a' && s[j] <= 'z') || (s[j] >= 'A' && s[j] <= 'Z') || (s[j] >= '0' && s[j] <= '9') || s[j] == '_') {
				j++
			}
			if j < len(s) && s[j] == '$' && (j == i+1 || !(s[i+1] >= '0' && s[i+1] <= '9')) {
				tag := s[i : j+1]
				k := strings.Index(s[j+1:], tag)
				if k < 0 {
					return "", errors.New("unterminated dollar quote")
				}
				i = j + 1 + k + len(tag)
			} else {
				i++
			}
		case (s[i] >= 'a' && s[i] <= 'z') || (s[i] >= 'A' && s[i] <= 'Z') || s[i] == '_' || s[i] >= 128:
			i++
			for i < len(s) && ((s[i] >= 'a' && s[i] <= 'z') || (s[i] >= 'A' && s[i] <= 'Z') || (s[i] >= '0' && s[i] <= '9') || s[i] == '_' || s[i] == '$' || s[i] >= 128) {
				i++
			}
			// E'...' is a PostgreSQL escape string: a backslash escapes the next byte.
			if i-start == 1 && (s[start] == 'e' || s[start] == 'E') && i < len(s) && s[i] == '\'' {
				i++
				closed := false
				for i < len(s) {
					if s[i] == '\\' {
						i += 2
						continue
					}
					if s[i] == '\'' {
						i++
						if i < len(s) && s[i] == '\'' {
							i++
							continue
						}
						closed = true
						break
					}
					i++
				}
				if !closed {
					return "", errors.New("unterminated SQL quote")
				}
			}
		case s[i] == '?':
			if i+1 < len(s) && s[i+1] >= '0' && s[i+1] <= '9' {
				return "", errors.New("numbered ? parameter is not supported for PostgreSQL")
			}
			n++
			fmt.Fprintf(&b, "$%d", n)
			i++
			continue
		default:
			i++
		}
		b.WriteString(s[start:i])
	}
	if hasNumbered && n > 0 {
		return "", errors.New("mixed SQL parameter styles")
	}
	return b.String(), nil
}

// InsertIgnore builds a single INSERT from a trusted VALUES or SELECT clause.
// Identifiers are restricted; source is SQL supplied by the caller, never data.
func (d Dialect) InsertIgnore(table string, columns []string, source string) (string, error) {
	if !d.valid() || !identifier.MatchString(table) || len(columns) == 0 {
		return "", errors.New("invalid insert")
	}
	for _, c := range columns {
		if !identifier.MatchString(c) {
			return "", errors.New("invalid column")
		}
	}
	s := strings.TrimSpace(source)
	upper := strings.ToUpper(s)
	if !(strings.HasPrefix(upper, "VALUES ") || strings.HasPrefix(upper, "VALUES(") || strings.HasPrefix(upper, "SELECT ")) || strings.Contains(s, ";") {
		return "", errors.New("unsupported insert source")
	}
	return d.Bind("INSERT INTO " + table + " (" + strings.Join(columns, ", ") + ") " + s + " ON CONFLICT DO NOTHING")
}
func (d Dialect) RowOrder(desc bool) (string, error) {
	if !d.valid() {
		return "", errors.New("unknown SQL dialect")
	}
	if desc {
		return "source_rowid DESC", nil
	}
	return "source_rowid ASC", nil
}
func (d Dialect) Identity() (string, error) {
	if !d.valid() {
		return "", errors.New("unknown SQL dialect")
	}
	return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", nil
}
func (d Dialect) Binary() (string, error) {
	if !d.valid() {
		return "", errors.New("unknown SQL dialect")
	}
	return "BYTEA", nil
}

var jsonPath = regexp.MustCompile(`^\$(\.[a-zA-Z0-9_]+)+$`)

func (d Dialect) jsonPath(column, path string) (string, []string, error) {
	if !d.valid() || !identifier.MatchString(column) || !jsonPath.MatchString(path) {
		return "", nil, errors.New("invalid JSON path")
	}
	return column, strings.Split(path[2:], "."), nil
}

// JSONText returns an expression reading the value at a constant path of a JSON
// text column as text: (col::jsonb #>> '{a,b}'). Compare numbers with JSONNumber,
// not JSONText.
func (d Dialect) JSONText(column, path string) (string, error) {
	col, keys, err := d.jsonPath(column, path)
	if err != nil {
		return "", err
	}
	return "(" + col + "::jsonb #>> '{" + strings.Join(keys, ",") + "}')", nil
}

// JSONNumber is JSONText for a numeric value: the text is cast to numeric so a
// numeric parameter can be compared. A non-numeric value makes PostgreSQL fail.
func (d Dialect) JSONNumber(column, path string) (string, error) {
	s, err := d.JSONText(column, path)
	if err != nil {
		return s, err
	}
	return s + "::numeric", nil
}

// TableExists returns a statement with one ? parameter (the table name, bound
// for the dialect) that yields one row with count > 0 when the table exists. The
// name is resolved through search_path with to_regclass.
func (d Dialect) TableExists() (string, error) {
	return d.Bind("SELECT count(*) FROM (SELECT to_regclass(?) AS found) t WHERE found IS NOT NULL")
}

// BeginWrite starts a transaction that will read and then write. Writers are
// serialized by WriteLock, not by the BEGIN statement.
func (d Dialect) BeginWrite() (string, error) {
	if !d.valid() {
		return "", errors.New("unknown SQL dialect")
	}
	return "BEGIN", nil
}

// WriteLock returns the statement a read-modify-write transaction runs right
// after BeginWrite, with one ? parameter (the lock name): a transaction-scoped
// advisory lock, released at COMMIT or ROLLBACK, because BEGIN alone lets two
// read-modify-write transactions interleave.
func (d Dialect) WriteLock() (string, error) {
	return d.Bind("SELECT pg_advisory_xact_lock(hashtext(?))")
}
