package appsql

import (
	"testing"
)

func TestDialectTable(t *testing.T) {
	cases := []struct {
		name string
		got  func() (string, error)
		want string
	}{
		{"postgres bind", func() (string, error) { return Postgres.Bind("SELECT ?, '?', \"?\", $$?$$, ? -- ?\n/* ? */") }, "SELECT $1, '?', \"?\", $$?$$, $2 -- ?\n/* ? */"},
		{"pg array", func() (string, error) { return Postgres.Bind("SELECT arr[?], a$b$, ?") }, "SELECT arr[$1], a$b$, $2"},
		{"pg tagged", func() (string, error) { return Postgres.Bind("SELECT $tag$?$tag$, ?, /* outer /* ? */ ? */ ?") }, "SELECT $tag$?$tag$, $1, /* outer /* ? */ ? */ $2"},
		{"pg numbered quoted", func() (string, error) { return Postgres.Bind("SELECT '$1', $$?$$, ? -- $2\n") }, "SELECT '$1', $$?$$, $1 -- $2\n"},
		{"pg escape string", func() (string, error) { return Postgres.Bind(`SELECT E'\'?\'', ?, e'a''?\\', ?`) }, `SELECT E'\'?\'', $1, e'a''?\\', $2`},
		{"pg ident ending in e", func() (string, error) { return Postgres.Bind(`SELECT name'?', ?`) }, `SELECT name'?', $1`},
		{"postgres values", func() (string, error) { return Postgres.InsertIgnore("items", []string{"id", "v"}, "VALUES (?, ?)") }, "INSERT INTO items (id, v) VALUES ($1, $2) ON CONFLICT DO NOTHING"},
		{"postgres select", func() (string, error) {
			return Postgres.InsertIgnore("items", []string{"id"}, "SELECT id FROM src WHERE id = ?")
		}, "INSERT INTO items (id) SELECT id FROM src WHERE id = $1 ON CONFLICT DO NOTHING"},
		{"pg order asc", func() (string, error) { return Postgres.RowOrder(false) }, "source_rowid ASC"}, {"pg order", func() (string, error) { return Postgres.RowOrder(true) }, "source_rowid DESC"},
		{"pg identity", Postgres.Identity, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"}, {"pg binary", Postgres.Binary, "BYTEA"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := c.got()
			if err != nil || got != c.want {
				t.Fatal("unexpected dialect output")
			}
		})
	}
	for _, s := range []string{"'broken", "/* broken", "$tag$broken"} {
		if _, err := Postgres.Bind(s); err == nil {
			t.Fatal("unterminated SQL accepted")
		}
	}
	for _, s := range []string{`SELECT E'\'`, `SELECT E'abc`} {
		if _, err := Postgres.Bind(s); err == nil {
			t.Fatal("unterminated escape string accepted")
		}
	}
	if _, err := Postgres.Bind("SELECT ?1"); err == nil {
		t.Fatal("numbered ? accepted for postgres")
	}
	if _, err := Postgres.Bind("SELECT ?, ?2"); err == nil {
		t.Fatal("numbered ? accepted for postgres")
	}
	if _, err := Postgres.Bind("SELECT $1, ?"); err == nil {
		t.Fatal("mixed parameters accepted")
	}
	if _, err := Postgres.InsertIgnore("x; DROP TABLE y", []string{"id"}, "VALUES (?)"); err == nil {
		t.Fatal("invalid identifier accepted")
	}
}

func TestDialectPostgresSyntax(t *testing.T) {
	cases := []struct {
		name string
		got  func() (string, error)
		want string
	}{
		{"pg text", func() (string, error) { return Postgres.JSONText("json", "$.issue.number") }, "(json::jsonb #>> '{issue,number}')"},
		{"pg single key", func() (string, error) { return Postgres.JSONText("json", "$.id") }, "(json::jsonb #>> '{id}')"},
		{"pg number", func() (string, error) { return Postgres.JSONNumber("json", "$.number") }, "(json::jsonb #>> '{number}')::numeric"},
		{"pg exists", Postgres.TableExists, "SELECT count(*) FROM (SELECT to_regclass($1) AS found) t WHERE found IS NOT NULL"},
		{"pg begin", Postgres.BeginWrite, "BEGIN"},
		{"pg lock", Postgres.WriteLock, "SELECT pg_advisory_xact_lock(hashtext($1))"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := c.got()
			if err != nil || got != c.want {
				t.Fatalf("unexpected dialect output %q, %v", got, err)
			}
		})
	}
	for _, bad := range [][2]string{{"json", "$"}, {"json", "$.a'b"}, {"json", "a.b"}, {"j;son", "$.a"}, {"json", "$.a[0]"}, {"json", "$..a"}} {
		if _, err := Postgres.JSONText(bad[0], bad[1]); err == nil {
			t.Fatalf("accepted %v", bad)
		}
	}
	if _, err := Dialect(9).JSONText("json", "$.a"); err == nil {
		t.Fatal("unknown dialect accepted")
	}
}
